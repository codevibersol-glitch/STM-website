// copy.md: every word on the page, in reading order, for review without opening the code.

import {
  COMMITMENT,
  FAB_LABEL,
  FAQ_COPY,
  FEATURES_COPY,
  FEEDBACK,
  FOOTER,
  HEADER_CTA,
  HERO,
  HOW,
  NAV,
  PRICING_COPY,
  RESULTS_COPY,
  SKIP_LINK,
  TIME_BACK,
  WHO,
} from '../data/copy';
import { FAQ } from '../data/faq';
import { FEATURES } from '../data/features';
import { GALLERY_COPY } from '../data/gallery';
import { PRICING, billingWords, formatPrice } from '../data/pricing';
import { SHOTS } from '../data/shots';
import { CREDITS, SITE_DESCRIPTION, SITE_TITLE, TELEGRAM_URL, TRADEMARK_NOTICE } from '../data/site';
import { RESULTS_LABEL, STATS, stat } from '../data/stats';
import { COMING_SOON, VERSIONS, VERSIONS_COPY } from '../data/versions';

export function copyDeck(): string {
  const hours = stat('hours');
  const lines: string[] = [
    '# STM website: the copy deck',
    '',
    '_Generated by `npm run build` from `src/data/` - edit the words there, not here._',
    '',
    '## Search and sharing',
    '',
    `- **Title:** ${SITE_TITLE} (${SITE_TITLE.length} characters)`,
    `- **Description:** ${SITE_DESCRIPTION} (${SITE_DESCRIPTION.length} characters)`,
    `- **The only outbound link:** ${TELEGRAM_URL}`,
    '',
    '## Header',
    '',
    `- Skip link: ${SKIP_LINK}`,
    `- Navigation: ${NAV.map((n) => n.label).join(' · ')}`,
    `- Button: ${HEADER_CTA}`,
    '- Accessibility menu: Text size (A, A+, A++) · High contrast · Reduce motion · Dyslexia-friendly font · Reset to default',
    '',
    '## Hero',
    '',
    `- Kicker: ${HERO.kicker}`,
    `- **H1:** ${HERO.titleBefore}${HERO.titleKeyword}${HERO.titleAfter}`,
    `- Lead: ${HERO.lead}`,
    `- Buttons: ${HERO.primaryCta} · ${HERO.secondaryCta}`,
    `- Trust line: ${HERO.trust.join(' · ')}`,
    `- Proof line: ${HERO.proofLead} ${stat('xp-median').value} ${stat('xp-median').unit} ${stat('xp-median').short ?? ''} · ${HERO.proofLink}`,
    `- Picture caption: ${HERO.caption}`,
    '',
    `## ${VERSIONS_COPY.title}`,
    '',
    `_${VERSIONS_COPY.eyebrow}_ - ${VERSIONS_COPY.intro}`,
    '',
    `- ${VERSIONS.join(' · ')}`,
    `- ${VERSIONS_COPY.soonLabel}: ${COMING_SOON.map((c) => c.name).join(' · ')}`,
    '',
    ...(SHOTS.length > 0
      ? [
          `## ${GALLERY_COPY.title}`,
          '',
          `_${GALLERY_COPY.eyebrow}_ - ${GALLERY_COPY.intro}`,
          '',
          ...SHOTS.map((s) => `- **${s.title}** - ${s.caption} (picture: ${s.alt})`),
          '',
          GALLERY_COPY.note,
          '',
        ]
      : []),
    `## ${WHO.title}`,
    '',
    `_${WHO.eyebrow}_ - ${WHO.intro}`,
    '',
    ...WHO.cards.flatMap((c) => [`- **${c.title}** - ${c.text}`]),
    '',
    `## ${HOW.title}`,
    '',
    `_${HOW.eyebrow}_`,
    '',
    ...HOW.steps.map((s, i) => `${i + 1}. **${s.title}** - ${s.text}`),
    '',
    `## ${FEATURES_COPY.title}`,
    '',
    `_${FEATURES_COPY.eyebrow}_ - ${FEATURES_COPY.intro}`,
    '',
    ...FEATURES.map((f) => `- **${f.title}** - ${f.text}`),
    '',
    `## ${RESULTS_COPY.title}`,
    '',
    `_${RESULTS_COPY.eyebrow}_ - ${RESULTS_COPY.intro} All numbers: ${RESULTS_LABEL}.`,
    '',
    ...STATS.map((s) => `- **${[s.prefix, s.value, s.unit].filter(Boolean).join(' ')}** ${s.label} (source ${s.marker}: ${s.source})`),
    '',
    `## ${TIME_BACK.title}`,
    '',
    `_${TIME_BACK.eyebrow}_ - ${TIME_BACK.before} ${hours.prefix} ${hours.value} ${TIME_BACK.unitWord} ${TIME_BACK.after} ${TIME_BACK.note}`,
    '',
    `## ${PRICING_COPY.title}`,
    '',
    `_${PRICING_COPY.eyebrow}_ - ${PRICING_COPY.intro}`,
    '',
    ...PRICING.plans.map(
      (p) =>
        `- **${p.name}** (${p.when}): ${formatPrice(p.price) ? `${formatPrice(p.price)} ${billingWords()}` : PRICING_COPY.priceOnTelegram}. ${p.note} Button: ${p.cta}`,
    ),
    '',
    `${PRICING_COPY.includesTitle}:`,
    '',
    ...PRICING.includes.map((i) => `- ${i}`),
    '',
    `${PRICING_COPY.stepsTitle}:`,
    '',
    ...PRICING.steps.map((s, i) => `${i + 1}. ${s}`),
    '',
    PRICING_COPY.note,
    '',
    `## ${COMMITMENT.title}`,
    '',
    ...COMMITMENT.paragraphs.flatMap((p) => [p, '']),
    ...COMMITMENT.points.map((p) => `- ${p}`),
    '',
    `Button: ${COMMITMENT.cta}`,
    '',
    `## ${FAQ_COPY.title}`,
    '',
    ...FAQ.flatMap((f) => [`**${f.q}**`, '', f.a, '']),
    `## ${FEEDBACK.title}`,
    '',
    FEEDBACK.intro,
    '',
    ...FEEDBACK.prompts.map((p) => `- **${p.title}** - ${p.hint}`),
    '',
    `${FEEDBACK.templateLabel}:`,
    '',
    '```',
    FEEDBACK.template.trimEnd(),
    '```',
    '',
    `Buttons: ${FEEDBACK.copy} (then "${FEEDBACK.copied}") · ${FEEDBACK.send}`,
    '',
    FEEDBACK.note,
    '',
    '## Footer',
    '',
    `- ${FOOTER.tagline}`,
    `- ${FOOTER.contact} @HugeKush`,
    `- ${FOOTER.privacy}`,
    `- ${TRADEMARK_NOTICE}`,
    `- ${CREDITS}`,
    '',
    `Phone button: ${FAB_LABEL}`,
    '',
  ];
  return lines.join('\n');
}
